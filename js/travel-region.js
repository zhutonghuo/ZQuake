/* travel-region.js — 区域走时修正表（P/S 波）
 *
 * ★★★ 2026-10-28 用户：「JMA2001 是日本的模型，中国的青藏高原、四川盆地、
 *   甚至太平洋海沟，地壳厚度和波速完全不同，用日本的速度模型去算中国地震的
 *   波前，物理上会严重失真吧」→ 选择方案 B（区域系数微调）。
 *
 * ── 数值从哪来（不是拍脑袋，可复现）──────────────────────────────
 *   ① 数据源：CRUST1.0（Laske, Masters, Ma & Pasyanos 2013）
 *      1°×1° 全球地壳模型，含 8 层（水/冰/3 层沉积/3 层结晶地壳）+ 莫霍面下 Vp/Vs。
 *      https://igppweb.ucsd.edu/~gabi/crust1.html
 *      本文件用的就是 crust1.vp / crust1.vs / crust1.bnds 原始格点值。
 *   ② 走时算法（经典解析式，已用两层模型解析解校准）：
 *        V_avg   = Σ h_i / Σ (h_i / V_i)           （地壳内调和平均速度）
 *        t_direct= √(X² + h_src²) / V_avg
 *        t_head  = X / V_moho + Σ_i 2·h_i·√(1/V_i² − 1/V_moho²)   （Pn / Sn）
 *        t(X)    = min(t_direct, t_head)
 *      X = 震央距(km)，h_src = 震源深 10 km（校准基准）。
 *   ③ 基准 = 日本本州格点（36.5N 138.5E）。
 *      交叉验证：该格点算出的 P 走时在 200/300/500 km = 31.6/44.6/70.6 s，
 *      而 app 内 JMA2001 表在同样距离 = 31.35/44.66/70.15 s → 相差 <1%，
 *      说明"区域比值"这套口径可以直接乘在 JMA2001 上。
 *   ④ k = t_region(X) / t_本州(X)，即「该区域相对日本快/慢多少」。
 *
 * ── 实测结果（格点 → k，X = 50/100/200/300/500 km）────────────────
 *   区域            Moho   沉积    k_P                      k_S
 *   青藏(拉萨)      66km   0.1km   1.00 1.00 1.02 1.08 1.08  0.98 0.98 0.99 1.05 1.06
 *   青藏(柴达木)    49km   0.8km   1.02 1.02 1.04 1.07 1.02  1.00 1.00 1.01 1.06 1.02
 *   川西(龙门山)    45km   0.0km   0.99 0.99 1.00 1.05 1.02  0.97 0.97 0.98 1.04 1.01
 *   四川盆地        41km   7.5km   1.04 1.04 1.06 1.02 0.99  1.04 1.04 1.06 1.03 1.00
 *   云南(滇西)      44km   0.7km   1.01 1.01 1.03 1.05 1.02  1.00 1.00 1.02 1.05 1.02
 *   华北(京津冀)    38km   2.7km   1.02 1.01 1.03 1.02 1.00  1.02 1.02 1.03 1.02 1.00
 *   华南(珠三角)    30km   0.0km   0.98 0.98 0.98 0.98 0.97  0.98 0.98 0.98 0.98 0.98
 *   台湾            40km   0.5km   1.02 1.02 1.04 1.04 1.02  1.09 1.09 1.08 1.06 1.03
 *   新疆(天山)      49km   0.5km   1.00 1.00 1.02 1.07 1.02  0.99 0.99 1.00 1.06 1.02
 *   东北(松辽)      31km   2.2km   1.02 1.02 0.99 0.98 0.97  1.03 1.03 0.99 0.98 0.97
 *   日本海沟(洋)    13km   0.3km   0.93 0.85 0.82 0.86 0.89  1.03 0.91 0.86 0.89 0.91
 *   太平洋(洋)      13km   0.2km   0.91 0.84 0.82 0.86 0.89  0.98 0.89 0.85 0.88 0.90
 *
 * ── 两条重要取舍 ─────────────────────────────────────────────
 *   ① **日本（含近海）一律 k = 1**。JMA2001 本来就是日本官方的走时表，
 *      近海地震的路径它已经标定过；再套"洋壳薄→更快"的修正会破坏
 *      官方 EEW 观感（用户明确说过「日本的是没问题的」）→ 海域那两行只作记录，不启用。
 *   ② 华南/华北 ≈ 1.00，说明克拉通地壳与日本差不多，**中国东部其实不需要修**，
 *      真正需要的是青藏/新疆/川滇（远场偏慢）与台湾（S 近场偏慢）。
 *
 * ── 已知局限（写在这里免得以后又吵）──────────────────────────
 *   · 只按**震中位置**选区域，不看射线路径穿越的构造（3D 效应做不到）
 *   · 深度只按 10 km 校准；深源事件套同一套 k（JMA2001 的深度带仍照旧生效）
 *   · CRUST1.0 是 1° 平均，局部盆地/断裂带细节被抹平
 */
(function (global) {
  'use strict';

  /* 距离结点（km）*/
  var KX = [50, 100, 200, 300, 500];

  /* 区域 → [k_P at KX, k_S at KX] */
  var ZONES = {
    /* 日本本土 + 近海：官方 JMA2001 就是这一带标定的 → 不动 */
    jp: null,
    other: null,

    /* 青藏区（西藏/青海/川西高原/滇西北/甘南）*/
    cn_qz: {
      p: [1.01, 1.01, 1.03, 1.07, 1.05],
      s: [0.99, 0.99, 1.00, 1.05, 1.04]
    },
    /* 川滇（四川盆地 + 龙门山 + 云南）*/
    cn_sw: {
      p: [1.01, 1.01, 1.03, 1.04, 1.01],
      s: [1.00, 1.00, 1.02, 1.04, 1.01]
    },
    /* 新疆区 */
    cn_xj: {
      p: [1.00, 1.00, 1.02, 1.07, 1.02],
      s: [0.99, 0.99, 1.00, 1.06, 1.02]
    },
    /* 东北（中强地震区）*/
    cn_mid: {
      p: [1.02, 1.02, 0.99, 0.98, 0.97],
      s: [1.03, 1.03, 0.99, 0.98, 0.97]
    },
    /* 华中/华北/华南/东南沿海（跟日本几乎一致）*/
    cn_east: {
      p: [1.00, 1.00, 1.00, 1.00, 0.99],
      s: [1.00, 1.00, 1.01, 1.00, 0.99]
    },
    /* 台湾（厚沉积 + 碰撞带，S 波近场明显偏慢）*/
    tw: {
      p: [1.02, 1.02, 1.04, 1.04, 1.02],
      s: [1.09, 1.09, 1.08, 1.06, 1.03]
    }
  };

  /** 震中 → 区域键（矩形近似，与 cn-gmpe.js 的分区口径保持一致）*/
  function zoneOf(lat, lon) {
    lat = +lat; lon = +lon;
    if (!isFinite(lat) || !isFinite(lon)) return 'other';

    /* 台湾本岛 + 周边 */
    if (lon >= 119.3 && lon <= 122.3 && lat >= 21.5 && lat <= 25.6) return 'tw';

    /* 日本列岛（本州/四国/九州/北海道/琉球）+ 其近海 → 不修正 */
    if (lon >= 127 && lon <= 147 && lat >= 24 && lat <= 46) return 'jp';
    /* 日本海沟/千岛外海一带也算日本的官方范围 */
    if (lon >= 141 && lon <= 155 && lat >= 30 && lat <= 50) return 'jp';

    /* 中国境内 */
    if (lon < 73 || lon > 135.5 || lat < 18 || lat > 54) return 'other';

    /* 新疆：73~96.5E，36.5~49.5N */
    if (lon >= 73 && lon <= 96.5 && lat >= 36.5 && lat <= 49.5) return 'cn_xj';

    /* 川滇：99~106.5E，21~34.5N（先于青藏判，四川盆地/云南都属于这档）*/
    if (lon >= 99 && lon <= 106.5 && lat >= 21 && lat <= 34.5) return 'cn_sw';

    /* 青藏：73~105E，26~36.5N；以及 96.5~104E，32~40N（青海）*/
    if (lon >= 73 && lon <= 105 && lat >= 26 && lat < 36.5) return 'cn_qz';
    if (lon > 96.5 && lon <= 104 && lat >= 32 && lat <= 40) return 'cn_qz';

    /* 东北 */
    if (lon >= 118 && lat >= 40) return 'cn_mid';

    /* 其余（华北/华中/华南/东南沿海）*/
    return 'cn_east';
  }

  /** 线性插值；超出结点范围按端点值封顶 */
  function interp(arr, x) {
    if (!arr) return 1;
    if (!(x > 0)) return arr[0];
    if (x <= KX[0]) return arr[0];
    if (x >= KX[KX.length - 1]) return arr[arr.length - 1];
    for (var i = 1; i < KX.length; i++) {
      if (x <= KX[i]) {
        var t = (x - KX[i - 1]) / (KX[i] - KX[i - 1]);
        return arr[i - 1] + (arr[i] - arr[i - 1]) * t;
      }
    }
    return arr[arr.length - 1];
  }

  /**
   * 区域走时系数 k：t_region = k × t_JMA2001
   * @param {number} lat 震中纬度
   * @param {number} lon 震中经度
   * @param {number} distKm 该点的震央距（km）
   * @param {boolean} isP true=P 波
   * @returns {number} k（1 = 与日本一致，不做修正）
   */
  function factor(lat, lon, distKm, isP) {
    var z = ZONES[zoneOf(lat, lon)];
    if (!z) return 1;
    return interp(isP ? z.p : z.s, +distKm || 0);
  }

  global.QVTravelK = {
    zoneOf: zoneOf,
    factor: factor,
    knots: KX,
    zones: ZONES,
    /* 便于自测/调试 */
    table: function (lat, lon) {
      var z = ZONES[zoneOf(lat, lon)];
      return z || { p: [1, 1, 1, 1, 1], s: [1, 1, 1, 1, 1] };
    }
  };
})(typeof window !== 'undefined' ? window : global);
